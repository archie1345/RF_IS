function interpolate(value: string, params: Record<string, string | number>): string {
    return value.replace(/:([a-zA-Z_][\w-]*)/g, (_, key: string) => String(params[key] ?? `:${key}`));
}

export function translate(key: string, locale: AppLocale = 'id', params: Record<string, string | number> = {}): string {
    const value =
        messages[locale][key] ??
        (locale === 'en' ? extendedEnglishMessages[key] : extendedIndonesianMessages[key]) ??
        key;
    return interpolate(typeof value === 'function' ? value(params) : value, params);
}

export function useI18n() {
    const page = usePage<SharedPageProps>();
    watch(
        () => page.props.locale,
        (value) => {
            activeLocale.value = value === 'en' ? 'en' : 'id';
            if (typeof document !== 'undefined') document.documentElement.lang = activeLocale.value;
        },
        { immediate: true },
    );
    const locale = computed<AppLocale>(() => activeLocale.value);

    return {
        locale,
        t: (key: string, params: Record<string, string | number> = {}) => {
            const translated = translate(key, locale.value, params);
            return locale.value === 'en' && translated === key ? translateText(key, locale.value) : translated;
        },
    };
}

const translationFragments = [...new Set([...Object.keys(messages.en), ...Object.keys(extendedEnglishMessages)])]
    .filter((key) => key.length >= 3 && !key.includes(':'))
    .sort((left, right) => right.length - left.length);

function translateText(source: string, locale: AppLocale): string {
    const exact = translate(source, locale);
    if (locale !== 'en' || exact !== source) return exact;

    // Text nodes containing interpolated names/counts are not exact dictionary
    // keys. Translate known Indonesian fragments inside those nodes as well.
    let rendered = source;
    translationFragments.forEach((fragment) => {
        if (!rendered.includes(fragment)) return;
        const translated = translate(fragment, locale);
        if (translated === fragment) return;

        if (/^[A-Za-z0-9_]+$/.test(fragment)) {
            let offset = 0;
            while (offset < rendered.length) {
                const index = rendered.indexOf(fragment, offset);
                if (index < 0) break;
                const before = rendered[index - 1];
                const after = rendered[index + fragment.length];
                const isWordCharacter = (value: string | undefined) => Boolean(value && /[A-Za-z0-9_]/.test(value));
                if (!isWordCharacter(before) && !isWordCharacter(after)) {
                    rendered = `${rendered.slice(0, index)}${translated}${rendered.slice(index + fragment.length)}`;
                    offset = index + translated.length;
                } else {
                    offset = index + fragment.length;
                }
            }
        } else {
            rendered = rendered.split(fragment).join(translated);
        }
    });

    return rendered;
}

const translatedRoots = new Set<HTMLElement>();
const translatedTextNodes = new WeakMap<Text, { source: string; rendered: string }>();
const translatedAttributes = new WeakMap<HTMLElement, Map<string, { source: string; rendered: string }>>();

function translateDom(root: HTMLElement): void {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes: Text[] = [];
    let current: Node | null;
    while ((current = walker.nextNode())) nodes.push(current as Text);

    nodes.forEach((node) => {
        const currentText = node.textContent ?? '';
        const previous = translatedTextNodes.get(node);
        const source = previous && currentText === previous.rendered ? previous.source : currentText;
        const trimmed = source.trim();
        if (!trimmed) return;
        const translated = translateText(trimmed, activeLocale.value);
        const start = source.indexOf(trimmed);
        const rendered = `${source.slice(0, start)}${translated}${source.slice(start + trimmed.length)}`;
        if (currentText !== rendered) node.textContent = rendered;
        translatedTextNodes.set(node, { source, rendered });
    });

    root.querySelectorAll<HTMLElement>('[placeholder], [title], [aria-label]').forEach((element) => {
        (['placeholder', 'title', 'aria-label'] as const).forEach((attribute) => {
            const value = element.getAttribute(attribute);
            if (!value) return;
            const elementAttributes = translatedAttributes.get(element) ?? new Map();
            const previous = elementAttributes.get(attribute);
            const source = previous && value === previous.rendered ? previous.source : value;
            const rendered = translateText(source, activeLocale.value);
            if (value !== rendered) element.setAttribute(attribute, rendered);
            elementAttributes.set(attribute, { source, rendered });
            translatedAttributes.set(element, elementAttributes);
        });
    });
}

export const translationDirective = {
    mounted(root: HTMLElement) {
        translatedRoots.add(root);
        queueMicrotask(() => translateDom(root));
    },
    unmounted(root: HTMLElement) {
        translatedRoots.delete(root);
    },
};

if (typeof window !== 'undefined') {
    const observer = new MutationObserver((mutations) => {
        queueMicrotask(() => {
            const addedRoots = new Set<HTMLElement>();
            mutations.forEach((mutation) => {
                mutation.addedNodes.forEach((node) => {
                    if (node instanceof HTMLElement) {
                        addedRoots.add(node);
                    } else if (node.parentElement) {
                        addedRoots.add(node.parentElement);
                    }
                });
            });
            addedRoots.forEach((root) => translateDom(root));
        });
    });

    if (document.body) observer.observe(document.body, { childList: true, subtree: true });
    watch(activeLocale, () => {
        translatedRoots.forEach((root) => translateDom(root));
    });
}
